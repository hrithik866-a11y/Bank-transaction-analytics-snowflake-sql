##  Snowflake Data Setup

The transaction dataset was loaded into Snowflake for data preparation, validation, and SQL-based analysis.

### Database Structure

BANK ANALYTICS
└── RAW DATA
    └── TRANSACTIONS

CREATE DATABASE BANK_ANALYTICS;
CREATE SCHEMA RAW_DATA;
USE DATABASE BANK_ANALYTICS;
USE SCHEMA BANK_ANALYTICS.RAW_DATA;


-- =====================================================
-- 01. DATA QUALITY CHECKS
-- =====================================================


#1) DATA QUALITY CHECKS

#Total number of records

SELECT COUNT(*) AS total_rows
FROM TRANSACTIONS;

#Checking Nulls

SELECT
COUNT_IF(CARD_ID IS NULL) AS card_id_nulls,
COUNT_IF(TRANSACTION_ID IS NULL) AS transaction_id_nulls,
COUNT_IF(AMOUNT IS NULL) AS transaction_amount_nulls,
COUNT_IF(MERCHANT_ID IS NULL) AS merchant_id_nulls,
COUNT_IF(MERCHANT_CITY IS NULL) AS city_nulls,
COUNT_IF(MERCHANT_STATE IS NULL) AS state_nulls
FROM TRANSACTIONS;

#Duplicate Transaction IDs

SELECT 
COUNT(*) AS total_rows,
COUNT(DISTINCT TRANSACTION_ID) AS unique_transaction_ids
FROM transactions;

# Duplicate transaction records

SELECT
COUNT(*) AS TOTAL_ROWS,
COUNT(DISTINCT
        TRANSACTION_ID,
        CARD_ID,
        AMOUNT,
        DATE,
        MERCHANT_ID
    ) AS UNIQUE_RECORDS,
    COUNT(*) - COUNT(DISTINCT
        TRANSACTION_ID,
        CARD_ID,
        AMOUNT,
        DATE,
        MERCHANT_ID
    ) AS DUPLICATE_RECORDS
FROM TRANSACTIONS;

#TRANSACTION amounts

SELECT
MIN(AMOUNT) AS MIN_AMOUNT,
MAX(AMOUNT) AS MAX_AMOUNT,
COUNT_IF(AMOUNT <= 0) AS NON_POSITIVE_AMOUNT
FROM TRANSACTIONS;

#Age values

SELECT 
MIN(CURRENT_AGE) AS min_age,
MAX(CURRENT_AGE) AS max_age,
COUNT_IF(CURRENT_AGE < 18 OR CURRENT_AGE > 100) AS INVALID_AGES
FROM transactions;

# Birth year check

SELECT 
MIN(BIRTH_YEAR) AS min_birth_year,
MAX(BIRTH_YEAR) AS max_birth_year,
COUNT_IF(BIRTH_YEAR < 1900 OR BIRTH_YEAR > YEAR(CURRENT_DATE())) AS INVALID_BIRTH_YEARS
FROM transactions

#Age vs Birth Year consistency

SELECT
COUNT(*) AS INVALID_AGE_BIRTH_YEAR
FROM TRANSACTIONS
WHERE YEAR(CURRENT_DATE()) - BIRTH_YEAR <> AGE;

#Check transaction dates

SELECT
MIN(DATE) AS EARLIEST_TRANSACTION,
MAX(DATE) AS LATEST_TRANSACTION,
COUNT(DISTINCT DATE) AS UNIQUE_TRANSACTION_DATES
FROM TRANSACTIONS;

#Future transaction dates

SELECT
COUNT_IF(DATE > CURRENT_DATE()) AS FUTURE_DATES
FROM TRANSACTIONS;


