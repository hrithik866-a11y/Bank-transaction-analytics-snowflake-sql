-- =====================================================
--  1) CARD ANALYSIS
-- =====================================================


-- 1. Most Valuable Cards

SELECT
    CARD_ID,
    COUNT(*) AS TRANSACTION_COUNT,
    ROUND(SUM(AMOUNT), 2) AS TOTAL_SPENDING,
    ROUND(AVG(AMOUNT), 2) AS AVG_TRANSACTION_VALUE
FROM TRANSACTIONS
GROUP BY CARD_ID
ORDER BY TOTAL_SPENDING DESC
LIMIT 10;


-- 2. Card Usage Frequency

WITH Cte1 AS (
    SELECT
        CARD_ID,
        COUNT(*) AS TRANSACTION_COUNT
    FROM TRANSACTIONS
    GROUP BY CARD_ID
)
SELECT
    CASE
        WHEN TRANSACTION_COUNT BETWEEN 1 AND 2
            THEN 'Low Frequency'
        WHEN TRANSACTION_COUNT BETWEEN 3 AND 4
            THEN 'Medium Frequency'
        ELSE 'High Frequency'
    END AS USAGE_GROUP,
    COUNT(*) AS CARD_COUNT
FROM Cte1
GROUP BY USAGE_GROUP
ORDER BY CARD_COUNT DESC;


-- 3. Card Usage vs Spending

WITH Cte1 AS (
    SELECT
    CARD_ID,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(AMOUNT) AS TOTAL_SPENDING,
    AVG(AMOUNT) AS AVG_TRANSACTION_VALUE
    FROM TRANSACTIONS
    GROUP BY CARD_ID
)
SELECT
CASE
WHEN TRANSACTION_COUNT BETWEEN 1 AND 2
THEN 'Low Frequency'
WHEN TRANSACTION_COUNT BETWEEN 3 AND 4
THEN 'Medium Frequency'
ELSE 'High Frequency'
END AS USAGE_GROUP,
COUNT(*) AS CARD_COUNT,
SUM(TRANSACTION_COUNT) AS TOTAL_TRANSACTIONS,
ROUND(SUM(TOTAL_SPENDING), 2) AS TOTAL_SPENDING,
ROUND(AVG(AVG_TRANSACTION_VALUE), 2) AS AVG_TRANSACTION_VALUE
FROM CTE1
GROUP BY USAGE_GROUP
ORDER BY TOTAL_SPENDING DESC;

