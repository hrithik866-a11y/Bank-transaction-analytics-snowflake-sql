-- 02. MERCHANT ANALYSIS
-- =====================================================


-- 1. Merchant Performance by Transaction Volume

SELECT
MERCHANT_ID,
COUNT(*) AS TRNX_COUNT
FROM TRANSACTIONS
GROUP BY MERCHANT_ID
ORDER BY TRNX_COUNT DESC
LIMIT 10;


-- 2. Top 10 Merchant Spending Concentration

WITH cte1 AS (
    SELECT
        MERCHANT_ID,
        SUM(AMOUNT) AS TOTAL_SPENDING
    FROM TRANSACTIONS
    GROUP BY MERCHANT_ID
    ORDER BY TOTAL_SPENDING DESC
    LIMIT 10
)
SELECT
    ROUND(SUM(TOTAL_SPENDING), 2) AS TOP_10_SPENDING,
    ROUND((SELECT SUM(AMOUNT) FROM TRANSACTIONS), 2)
        AS OVERALL_SPENDING,
    ROUND(
        SUM(TOTAL_SPENDING)
        / (SELECT SUM(AMOUNT) FROM TRANSACTIONS) * 100,
        2
    ) AS PERCENTAGE
FROM cte1;


