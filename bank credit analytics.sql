-- =====================================================
-- 04. SPENDING ANALYSIS
-- =====================================================


-- 1. Transaction Size Analysis

SELECT
CASE
WHEN AMOUNT <= 1000 THEN '0-1000'
WHEN AMOUNT <= 5000 THEN '1001-5000'
WHEN AMOUNT <= 10000 THEN '5001-10000'
WHEN AMOUNT <= 15000 THEN '10001-15000'
ELSE 'Above 15000'
END AS SPENDING_RANGE,
COUNT(*) AS TRANSACTION_COUNT,
ROUND(SUM(AMOUNT), 2) AS TOTAL_SPENDING,
ROUND(
        COUNT(*) * 100.0 / SUM(COUNT(*)) OVER(),
        2
    ) AS TRANSACTION_PERCENTAGE

FROM TRANSACTIONS
GROUP BY 1
ORDER BY MIN(AMOUNT);


-- 2. Monthly Spending Trends

SELECT
    DATE_TRUNC('MONTH', DATE) AS MONTH,
    COUNT(*) AS TRANSACTION_COUNT,
    ROUND(SUM(AMOUNT), 2) AS TOTAL_SPENDING
FROM TRANSACTIONS
GROUP BY DATE_TRUNC('MONTH', DATE)
ORDER BY MONTH;


-- 3. Month-over-Month Spending Growth

WITH CTE1 AS (
    SELECT
        DATE_TRUNC('MONTH', DATE) AS MONTH,
        SUM(AMOUNT) AS TOTAL_SPENDING
    FROM TRANSACTIONS
    GROUP BY DATE_TRUNC('MONTH', DATE)
)
SELECT
    MONTH,
    ROUND(TOTAL_SPENDING, 2) AS TOTAL_SPENDING,
    ROUND(
        (
            TOTAL_SPENDING
            - LAG(TOTAL_SPENDING) OVER (ORDER BY MONTH)
        )
        / LAG(TOTAL_SPENDING) OVER (ORDER BY MONTH) * 100,
        2
    ) AS MOM_PERCENT_CHANGE
FROM CTE1
ORDER BY MONTH;

-- =====================================================
-- 06. TIME-BASED ANALYSIS
-- =====================================================


-- 1. Weekend vs Weekday Spending

SELECT
    CASE
        WHEN DAYOFWEEK(DATE) IN (1, 7)
            THEN 'Weekend'
        ELSE 'Weekday'
    END AS DAY_TYPE,

    COUNT(*) AS TRANSACTION_COUNT,

    ROUND(SUM(AMOUNT), 2) AS TOTAL_SPENDING,

    ROUND(AVG(AMOUNT), 2) AS AVG_TRANSACTION_VALUE

FROM TRANSACTIONS
GROUP BY DAY_TYPE
ORDER BY TOTAL_SPENDING DESC;

-- 2. Day-of-Week Analysis

SELECT
DAYNAME(DATE) AS DAY_NAME,
COUNT(*) AS TRANSACTION_COUNT,
ROUND(SUM(AMOUNT), 2) AS TOTAL_SPENDING,
ROUND(AVG(AMOUNT), 2) AS AVG_TRANSACTION_VALUE
FROM TRANSACTIONS
GROUP BY DAY_NAME
ORDER BY TOTAL_SPENDING DESC;

-- =====================================================
-- 07. HIGH-VALUE TRANSACTION ANALYSIS
-- =====================================================


-- 1. Top 10 Highest-Value Transactions

SELECT
CARD_ID,
AMOUNT,
MERCHANT_ID,
MERCHANT_CITY,
MERCHANT_STATE
FROM TRANSACTIONS
ORDER BY AMOUNT DESC
LIMIT 10;


-- 2. Highest-Value Transactions by State

SELECT
MERCHANT_STATE,
COUNT(*) AS HIGH_VALUE_TRANSACTIONS,
ROUND(MAX(AMOUNT), 2) AS HIGHEST_TRANSACTION,
ROUND(AVG(AMOUNT), 2) AS AVG_TRANSACTION_VALUE
FROM TRANSACTIONS
WHERE AMOUNT >= 10000
GROUP BY MERCHANT_STATE
ORDER BY HIGHEST_TRANSACTION DESC;

